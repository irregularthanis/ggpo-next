#!/usr/bin/env python3
"""Turn services/matchmaking/protocol_vectors.json into C++ checks.

The generated file defines CheckProtocolVectors(): for every vector it decodes
the wire bytes with the C++ client codec, compares each field with the vector,
and re-encodes to the identical bytes. The Python server tests decode the same
file, so client and server cannot drift apart.
"""

import json
import sys

TYPES = {"JOIN": "kJoin", "WAITING": "kWaiting", "MATCH": "kMatch", "BIND": "kBind",
         "BOUND": "kBound", "HELLO": "kHello", "ERROR": "kError",
         "PEERS_REQUEST": "kPeersRequest", "PEERS": "kPeers"}


def endpoint(expr, candidate):
    ip, port = candidate
    a, b, c, d = (int(x) for x in ip.split("."))
    return f"SameEndpoint({expr}, MakeEndpoint({a}, {b}, {c}, {d}, {port}))"


def checks(vector):
    f, out = vector["fields"], []
    for name in ("nonce", "token"):
        if name in f:
            out.append(f"m.{name} == {f[name]}ULL")
    for name in ("platform", "group_size", "joined", "player", "code"):
        if name in f:
            out.append(f"m.{name} == {f[name]}")
    if "lobby" in f:
        out.append(f'strcmp(m.lobby, "{f["lobby"].upper()}") == 0')
    if "relay_ports" in f:
        out.append(f"m.count == {len(f['relay_ports'])}")
        out += [f"m.relay_ports[{i}] == {port}" for i, port in enumerate(f["relay_ports"])]
        out += [f"m.platforms[{i}] == {value}" for i, value in enumerate(f["platforms"])]
    if vector["type"] == "PEERS_REQUEST":
        out.append(endpoint("m.lan", f["lan"]))
    if vector["type"] == "PEERS":
        out.append(f"m.count == {len(f['public'])}")
        out += [endpoint(f"m.public_candidates[{i}]", c) for i, c in enumerate(f["public"])]
        out += [endpoint(f"m.lan_candidates[{i}]", c) for i, c in enumerate(f["lan"])]
    return out


def main():
    source, target = sys.argv[1], sys.argv[2]
    vectors = json.load(open(source, encoding="utf-8"))["vectors"]
    lines = ["/* Generated by tests/vectorwar/gen_net_vectors.py; do not edit. */",
             "static int CheckProtocolVectors()", "{", "   int vectors = 0;"]
    for vector in vectors:
        wire = bytes.fromhex(vector["hex"])
        name = vector["name"]
        lines += ["   {",
                  "      static const uint8_t wire[] = { " + ", ".join(str(b) for b in wire) + " };",
                  "      Message m;",
                  f'      CHECK(Decode(wire, sizeof(wire), &m), "{name}: decode");',
                  f'      CHECK(m.type == {TYPES[vector["type"]]}, "{name}: type");']
        for condition in checks(vector):
            lines.append(f'      CHECK({condition}, "{name}: {condition.replace(chr(34), "")}");')
        lines += ["      uint8_t out[kMaxMessageSize];",
                  "      const size_t size = Encode(m, out, sizeof(out));",
                  f'      CHECK(size == sizeof(wire) && memcmp(out, wire, size) == 0, "{name}: re-encode");',
                  "      ++vectors;",
                  "   }"]
    lines += ["   return vectors;", "}", ""]
    with open(target, "w", encoding="utf-8") as output:
        output.write("\n".join(lines))


if __name__ == "__main__":
    main()
