#!/usr/bin/env python3
"""Validate deterministic peer results without trusting native struct layout."""

import json
import struct
from pathlib import Path


SCHEMA_VERSION = 2
REQUIRED_SCHEMA2_FIELDS = {
    "schema", "scenario", "run_id", "session_id", "player", "platform",
    "frames", "canonical_checksum", "native_checksum", "saves", "loads",
    "replay_frames", "running_events", "unexpected_disconnects",
    "session_closed", "exit_code",
}


def canonical_bytes(frame, accumulator, disconnect_flags=0):
    """Serialize the portable guest-state oracle as three little-endian u32s."""
    return struct.pack("<III", frame & 0xFFFFFFFF, accumulator & 0xFFFFFFFF,
                       disconnect_flags & 0xFFFFFFFF)


def fnv1a32(payload):
    """Return the same unsigned FNV-1a checksum used by the native fixture."""
    checksum = 2166136261
    for value in payload:
        checksum ^= value
        checksum = (checksum * 16777619) & 0xFFFFFFFF
    return checksum


def canonical_checksum(frame, accumulator, disconnect_flags=0):
    """Hash the explicitly serialized deterministic state."""
    return fnv1a32(canonical_bytes(frame, accumulator, disconnect_flags))


def input_for_player(player, frame):
    """Reproduce the deterministic input generated by each smoke peer."""
    return ((frame + 1) * (player * 17 + 3)) ^ (frame << player)


def expected_state(frames):
    """Independently advance the public smoke-state transition for N frames."""
    accumulator = 0
    for frame in range(frames):
        accumulator = (
            accumulator * 33
            + input_for_player(1, frame) * 3
            + input_for_player(2, frame) * 5
            + frame
        ) & 0xFFFFFFFF
    return {
        "frame": frames,
        "accumulator": accumulator,
        "disconnect_flags": 0,
        "canonical_checksum": canonical_checksum(frames, accumulator),
    }


def load_result(path):
    """Load one peer result and report malformed JSON with its artifact path."""
    path = Path(path)
    try:
        result = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        raise ValueError(f"{path}: invalid result artifact: {error}") from error
    if not isinstance(result, dict):
        raise ValueError(f"{path}: result must be a JSON object")
    return result


def _require_schema2(result, label):
    missing = sorted(REQUIRED_SCHEMA2_FIELDS - result.keys())
    if missing:
        raise ValueError(f"{label}: missing fields: {', '.join(missing)}")
    if result["schema"] != SCHEMA_VERSION:
        raise ValueError(f"{label}: unsupported schema {result['schema']!r}")


def validate_pair(peer_a, peer_b, frames, scenario=None, run_id=None,
                  session_id=None, platforms=None):
    """Validate identity, lifecycle, platform roles, and deterministic state."""
    peers = [peer_a, peer_b]
    if all("schema" not in peer for peer in peers):
        if [peer.get("player") for peer in peers] != [1, 2]:
            raise ValueError(f"unexpected players: {peers}")
        if any(peer.get("frame") != frames for peer in peers):
            raise ValueError(f"incomplete frames: {peers}")
        if peer_a.get("checksum") != peer_b.get("checksum"):
            raise ValueError(f"peer checksum mismatch: {peers}")
        if any(peer.get("running_events") != 1 for peer in peers):
            raise ValueError(f"unexpected running events: {peers}")
        return {"schema": 1, "frames": frames,
                "checksum": peer_a["checksum"], "peers": peers,
                "result": "pass"}

    for index, peer in enumerate(peers, start=1):
        _require_schema2(peer, f"peer {index}")
    if [peer["player"] for peer in peers] != [1, 2]:
        raise ValueError(f"unexpected players: {peers}")
    for field, expected in (("scenario", scenario), ("run_id", run_id),
                            ("session_id", session_id)):
        values = [peer[field] for peer in peers]
        if values[0] != values[1] or (expected is not None and values[0] != expected):
            raise ValueError(f"{field} mismatch: {values}")
    if platforms is not None and [peer["platform"] for peer in peers] != list(platforms):
        raise ValueError(f"platform-role mismatch: {peers}")
    if any(peer["frames"] != frames for peer in peers):
        raise ValueError(f"incomplete frames: {peers}")

    oracle = expected_state(frames)["canonical_checksum"]
    checksums = [peer["canonical_checksum"] for peer in peers]
    if checksums != [oracle, oracle]:
        raise ValueError(
            f"canonical checksum mismatch: peers={checksums}, oracle={oracle}"
        )
    for index, peer in enumerate(peers, start=1):
        if peer["running_events"] != 1:
            raise ValueError(f"peer {index}: running_events must equal 1")
        if peer["unexpected_disconnects"] != 0:
            raise ValueError(f"peer {index}: unexpected disconnect recorded")
        if peer["session_closed"] is not True:
            raise ValueError(f"peer {index}: session did not close cleanly")
        if peer["exit_code"] != 0:
            raise ValueError(f"peer {index}: nonzero recorded exit code")

    return {
        "schema": SCHEMA_VERSION,
        "scenario": peer_a["scenario"],
        "run_id": peer_a["run_id"],
        "session_id": peer_a["session_id"],
        "frames": frames,
        "canonical_checksum": oracle,
        "platforms": [peer["platform"] for peer in peers],
        "peers": peers,
        "result": "pass",
    }
